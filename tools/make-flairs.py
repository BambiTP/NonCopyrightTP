F = []  # (category, name, description, extra, grid)
def flair(cat, name, desc, extra, art):
    rows = [r for r in art.strip('\n').split('\n')]
    rows = [r.strip() for r in rows]
    bad = [i for i, r in enumerate(rows) if len(r) != 16]
    assert len(rows) == 16 and not bad, (name, bad)
    F.append((cat, name, desc, extra, rows))

