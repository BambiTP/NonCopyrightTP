# degree flairs: the number in a 3x5 pixel font on a coloured tag
DIGITS = {
    '0': ['www', 'w.w', 'w.w', 'w.w', 'www'], '1': ['.w.', 'ww.', '.w.', '.w.', 'www'],
    '3': ['www', '..w', '.ww', '..w', 'www'], '5': ['www', 'w..', 'www', '..w', 'www'],
    '6': ['www', 'w..', 'www', 'w.w', 'www'], '8': ['www', 'w.w', 'www', 'w.w', 'www'],
}
def degree(n, col, dark):
    s = str(n)
    g = [['.'] * 16 for _ in range(16)]
    for y in range(3, 13):
        for x in range(0, 16):
            g[y][x] = 'k' if y in (3, 12) or x in (0, 15) else (dark if y == 11 else col)
    width = len(s) * 4 - 1
    x0 = (16 - width) // 2
    for i, ch in enumerate(s):
        for dy, row in enumerate(DIGITS[ch]):
            for dx, p in enumerate(row):
                if p == 'w': g[5 + dy][x0 + i * 4 + dx] = 'w'
    return '\n' + '\n'.join(''.join(r) for r in g)

for n, col, dark in ((10, 'g', 'G'), (50, 'b', 'B'), (100, 'p', 'P'), (180, 'o', 'O'), (360, 'r', 'R')):
    flair('degree', str(n), f'{n} Degrees', 'Casual wins.', degree(n, col, dark))

sheet = Image.new('RGBA', (COLS * 16, ((len(F) + COLS - 1) // COLS) * 16), (0, 0, 0, 0))
out = []
for i, (cat, name, desc, extra, rows) in enumerate(F):
    x, y = i % COLS, i // COLS
    for py, row in enumerate(rows):
        for px, ch in enumerate(row):
            if ch != '.':
                h = PAL[ch]
                sheet.putpixel((x * 16 + px, y * 16 + py), (int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16), 255))
    out.append({'category': cat, 'name': name, 'x': x, 'y': y, 'description': desc, 'extra': extra,
                'key': f'{cat}.{name}', 'className': f'{cat}-{name}'})
sheet.save(os.path.join(ROOT, 'public', 'images', 'flair.png'))
with open(os.path.join(ROOT, 'server', 'flairs.json'), 'w') as f:
    json.dump(out, f, indent=1)
print(len(out), 'flairs')
